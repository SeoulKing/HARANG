(() => {
  'use strict';
  const locales = window.HarangLocales;
  const storageKey = 'harang.language';
  const supported = value => value === 'ko' || value === 'en';
  const requested = new URLSearchParams(window.location.search).get('lang');
  let saved;
  try { saved = window.localStorage.getItem(storageKey); } catch {}
  let language = supported(requested) ? requested : supported(saved) ? saved : navigator.language.toLowerCase().startsWith('ko') ? 'ko' : 'en';

  function t(key) { return locales[language].ui[key] ?? locales.ko.ui[key]; }
  function applyLanguage(next, updateAddress = false) {
    if (!supported(next)) return;
    language = next;
    document.documentElement.lang = language;
    document.body.dataset.lang = language;
    document.querySelectorAll('[data-i18n-html]').forEach(element => {
      const key = element.dataset.i18nHtml;
      element.innerHTML = locales[language].static[key] ?? locales.ko.static[key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
      element.placeholder = t(element.dataset.i18nPlaceholder);
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
      element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
    });
    document.querySelectorAll('[data-language]').forEach(button => {
      const active = button.dataset.language === language;
      button.setAttribute('aria-pressed', String(active));
      button.classList.toggle('active', active);
    });
    document.title = t('pageTitle');
    document.querySelector('meta[name="description"]').content = t('pageDescription');
    document.querySelector('meta[property="og:title"]').content = t('ogTitle');
    document.querySelector('meta[property="og:description"]').content = t('ogDescription');
    try { window.localStorage.setItem(storageKey, language); } catch {}
    if (updateAddress) {
      const address = new URL(window.location.href);
      address.searchParams.set('lang', language);
      try { window.history.replaceState(null, '', address); } catch {}
    }
    window.dispatchEvent(new CustomEvent('harang:languagechange', { detail: { language } }));
  }
  window.HarangI18n = {
    t,
    setLanguage: next => applyLanguage(next, true),
    get language() { return language; },
    get content() { return locales[language]; }
  };
  document.querySelectorAll('[data-language]').forEach(button => {
    button.addEventListener('click', () => applyLanguage(button.dataset.language, true));
  });
  window.addEventListener('popstate', () => {
    const requestedLanguage = new URLSearchParams(window.location.search).get('lang');
    if (supported(requestedLanguage)) applyLanguage(requestedLanguage);
  });
  applyLanguage(language);
})();

